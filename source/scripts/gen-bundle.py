#!/usr/bin/env python3
"""Generate the web bundle manifest (SHA-256 per file) + config.js.

The manifest is what makes file-level delta updates possible: the app
compares each remote hash against what it already has and downloads only
the files that actually changed.
"""
import argparse, hashlib, json, os, sys, datetime

p = argparse.ArgumentParser()
p.add_argument('--www', required=True)
p.add_argument('--web-version', type=int, default=1)
p.add_argument('--version-name', default='1.0.0')
p.add_argument('--version-code', type=int, default=1)
p.add_argument('--base-url', default='')
p.add_argument('--sources', default='https://glitchyapi.github.io/satlok-seva/manifest.json,'
                                    'https://raw.githubusercontent.com/glitchyapi/satlok-seva/main/release/manifest.json')
a = p.parse_args()

files = []
for root, dirs, names in os.walk(a.www):
    dirs[:] = [d for d in dirs if not d.startswith('.')]
    for n in sorted(names):
        if n in ('config.js', 'bundle-manifest.json') or n.startswith('.'):
            continue
        full = os.path.join(root, n)
        rel = os.path.relpath(full, a.www).replace(os.sep, '/')
        data = open(full, 'rb').read()
        files.append({
            'path': rel,
            'sha256': hashlib.sha256(data).hexdigest(),
            'size': len(data),
        })
files.sort(key=lambda f: f['path'])
total = sum(f['size'] for f in files)

manifest = {
    'version': a.web_version,
    'entry': 'index.html',
    'baseUrl': a.base_url,
    'generatedAt': datetime.datetime.utcnow().isoformat() + 'Z',
    'fileCount': len(files),
    'totalBytes': total,
    'files': files,
}
with open(os.path.join(a.www, 'bundle-manifest.json'), 'w', encoding='utf-8') as f:
    json.dump(manifest, f, indent=2, ensure_ascii=False)

cfg = {
    'versionName': a.version_name,
    'versionCode': a.version_code,
    'webVersion': a.web_version,
    'defaultLang': 'hi',
    'updateSources': [s.strip() for s in a.sources.split(',') if s.strip()],
    'buildTime': datetime.datetime.utcnow().isoformat() + 'Z',
}
js = ('/* generated by gen-bundle.py — do not edit by hand */\n'
      'window.WEB_VERSION = %d;\n'
      'window.APP_CONFIG = %s;\n'
      'window.BUNDLE_MANIFEST = %s;\n') % (
        a.web_version,
        json.dumps(cfg, ensure_ascii=False),
        json.dumps(manifest, ensure_ascii=False, separators=(',', ':')))
with open(os.path.join(a.www, 'config.js'), 'w', encoding='utf-8') as f:
    f.write(js)

print('  · %d files, %.1f KB total, web v%d' % (len(files), total / 1024.0, a.web_version))
