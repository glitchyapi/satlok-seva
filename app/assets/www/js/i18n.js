window.Lang = {
  code: "hi",
  available: ["hi", "en", "pa", "hr"],
  set(code) {
    if (!window.I18N[code]) code = "hi";
    this.code = code;
    document.documentElement.lang = code === "pa" ? "pa" : "hi";
    try { localStorage.setItem("ss_lang", code); } catch (e) {}
  },
  load() {
    let c = null;
    try { c = localStorage.getItem("ss_lang"); } catch (e) {}
    if (!c) {
      const n = (navigator.language || "hi").toLowerCase();
      c = n.startsWith("pa") ? "pa" : n.startsWith("en") ? "en" : "hi";
    }
    this.set(c);
  },
  dict() { return window.I18N[this.code] || window.I18N.hi; },
  get(key, vars) {
    const d = this.dict();
    let s = d[key];
    if (s === undefined) s = window.I18N.en[key];
    if (s === undefined) s = window.I18N.hi[key];
    if (s === undefined) return key;
    if (typeof s !== "string") return s;
    if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
    return s;
  }
};
window.t = (k, v) => window.Lang.get(k, v);
